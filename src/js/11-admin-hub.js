    function renderWeekRoomBadges(rooms, groups) {
      if (!rooms) return "";
      const activeBadges = (groups || []).filter(g => rooms[g.letter] && rooms[g.letter].trim() !== "").map(g =>
        `<span class="inline-flex items-center px-1.5 py-0.5 rounded text-[10px] font-mono font-bold bg-slate-100 text-slate-700 border border-slate-200">Grp ${g.letter}: ${rooms[g.letter]}</span>`
      );
      if (activeBadges.length === 0) return "";
      return `<span class="inline-flex flex-wrap items-center gap-1 ml-1.5">${activeBadges.join("")}</span>`;
    }

